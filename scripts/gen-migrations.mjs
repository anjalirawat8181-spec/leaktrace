import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'db', 'migrations');
const files = fs.readdirSync(dir).filter((f) => f.endsWith('.sql')).sort();

const entries = files.map((file) => {
  const text = fs.readFileSync(path.join(dir, file), 'utf8');
  const up = text.split('-- Down Migration')[0].replace('-- Up Migration', '').trim();
  return { name: file.replace(/\.sql$/, ''), sql: up };
});

const body = entries
  .map((e) => `  { name: ${JSON.stringify(e.name)}, sql: ${JSON.stringify(e.sql)} },`)
  .join('\n');

const out = `// Generated by scripts/gen-migrations.mjs from db/migrations/*.sql. Do not edit by hand.
export interface EmbeddedMigration { name: string; sql: string }

export const MIGRATIONS: EmbeddedMigration[] = [
${body}
];
`;
fs.writeFileSync(path.join(root, 'apps', 'api', 'src', 'migrations.generated.ts'), out);
console.log(`Embedded ${entries.length} migrations`);
